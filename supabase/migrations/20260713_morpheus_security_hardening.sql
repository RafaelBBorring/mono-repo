CREATE OR REPLACE FUNCTION public.create_morpheus_clinic(clinic_name TEXT)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  new_id UUID;
  account_email TEXT;
  account_name TEXT;
  current_count INTEGER;
  workspace_limit INTEGER;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'authentication_required'; END IF;
  IF length(trim(clinic_name)) < 2 THEN RAISE EXCEPTION 'invalid_clinic_name'; END IF;

  SELECT email, display_name INTO account_email, account_name FROM public.users WHERE id = auth.uid();
  SELECT count(*) INTO current_count FROM public.clinic_doctors WHERE user_id = auth.uid() AND role = 'admin';
  SELECT COALESCE(max(public.morpheus_plan_limit(clinic_id, 'workspaces')), 1)
    INTO workspace_limit
    FROM public.clinic_doctors
    WHERE user_id = auth.uid() AND role = 'admin';
  IF current_count >= workspace_limit THEN RAISE EXCEPTION 'workspace_plan_limit'; END IF;

  INSERT INTO public.clinics (name, admin_email, admin_password_hash, user_id, stripe_status, billing_enforced)
  VALUES (trim(clinic_name), account_email, '', auth.uid(), 'inactive', true)
  RETURNING id INTO new_id;

  INSERT INTO public.clinic_doctors (clinic_id, user_id, email, password_hash, display_name, role)
  VALUES (new_id, auth.uid(), account_email, '', COALESCE(account_name, trim(clinic_name)), 'admin');
  RETURN new_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.accept_morpheus_invitation(invitation_token TEXT)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  invitation public.clinic_invitations%ROWTYPE;
  account_email TEXT;
  account_name TEXT;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'authentication_required'; END IF;
  SELECT email, display_name INTO account_email, account_name FROM public.users WHERE id = auth.uid();
  SELECT * INTO invitation
  FROM public.clinic_invitations
  WHERE token = invitation_token AND accepted = false AND expires_at > now()
  FOR UPDATE;
  IF invitation.id IS NULL OR lower(invitation.email) <> lower(account_email) THEN RAISE EXCEPTION 'invalid_invitation'; END IF;

  INSERT INTO public.clinic_doctors (clinic_id, user_id, psychologist_id, email, password_hash, display_name, role)
  VALUES (invitation.clinic_id, auth.uid(), invitation.psychologist_id, account_email, '', account_name, invitation.role)
  ON CONFLICT (clinic_id, email) DO UPDATE SET user_id = auth.uid(), psychologist_id = EXCLUDED.psychologist_id, role = EXCLUDED.role;
  UPDATE public.clinic_invitations SET accepted = true WHERE id = invitation.id;
  RETURN invitation.clinic_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.invite_morpheus_doctor(target_clinic UUID, doctor_name TEXT, doctor_email TEXT)
RETURNS TABLE(psychologist_id INTEGER, invitation_token TEXT, linked BOOLEAN)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  account_id UUID;
  new_psychologist_id INTEGER;
  new_token TEXT;
  clean_email TEXT := lower(trim(doctor_email));
  clean_name TEXT := trim(doctor_name);
  initials_value TEXT;
BEGIN
  IF NOT public.is_clinic_admin(target_clinic) THEN RAISE EXCEPTION 'admin_required'; END IF;
  IF clean_name = '' OR clean_email !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' THEN RAISE EXCEPTION 'invalid_doctor'; END IF;
  IF EXISTS (SELECT 1 FROM public.clinic_doctors WHERE clinic_id = target_clinic AND lower(email) = clean_email) THEN RAISE EXCEPTION 'doctor_already_member'; END IF;

  initials_value := upper(left(regexp_replace(clean_name, '^(dr|dra)\.?\s+', '', 'i'), 1));
  INSERT INTO public.psychologists (clinic_id, name, short_name, initials, email, hex, rgb, light_hex, light_rgb)
  VALUES (target_clinic, clean_name, regexp_replace(clean_name, '^(dr|dra)\.?\s+', '', 'i'), COALESCE(NULLIF(initials_value, ''), 'PS'), clean_email, '#8fae9b', '143,174,155', '#3f6b5b', '63,107,91')
  RETURNING id INTO new_psychologist_id;

  SELECT id INTO account_id FROM public.users WHERE lower(email) = clean_email;
  IF account_id IS NOT NULL THEN
    INSERT INTO public.clinic_doctors (clinic_id, user_id, psychologist_id, email, password_hash, display_name, role)
    VALUES (target_clinic, account_id, new_psychologist_id, clean_email, '', clean_name, 'doctor');
    RETURN QUERY SELECT new_psychologist_id, NULL::TEXT, true;
  ELSE
    INSERT INTO public.clinic_invitations (clinic_id, psychologist_id, email, role)
    VALUES (target_clinic, new_psychologist_id, clean_email, 'doctor')
    RETURNING token INTO new_token;
    RETURN QUERY SELECT new_psychologist_id, new_token, false;
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_morpheus_workspace_counts()
RETURNS TABLE(clinic_id UUID, room_count BIGINT, doctor_count BIGINT)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT membership.clinic_id,
    (SELECT count(*) FROM public.rooms room WHERE room.clinic_id = membership.clinic_id),
    (SELECT count(*) FROM public.psychologists psychologist WHERE psychologist.clinic_id = membership.clinic_id)
  FROM public.clinic_doctors membership
  WHERE membership.user_id = auth.uid();
$$;

CREATE OR REPLACE FUNCTION public.enforce_morpheus_entity_limits()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE current_count INTEGER;
BEGIN
  IF TG_TABLE_NAME = 'rooms' THEN
    SELECT count(*) INTO current_count FROM public.rooms WHERE clinic_id = NEW.clinic_id;
    IF current_count >= public.morpheus_plan_limit(NEW.clinic_id, 'rooms') THEN RAISE EXCEPTION 'room_plan_limit'; END IF;
  ELSIF TG_TABLE_NAME = 'psychologists' THEN
    SELECT count(*) INTO current_count FROM public.psychologists WHERE clinic_id = NEW.clinic_id;
    IF current_count >= public.morpheus_plan_limit(NEW.clinic_id, 'doctors') THEN RAISE EXCEPTION 'doctor_plan_limit'; END IF;
  END IF;
  RETURN NEW;
END;
$$;

