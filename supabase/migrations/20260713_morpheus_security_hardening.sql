SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.clinics
    WHERE id = target_clinic
      AND (
        billing_enforced = false
        OR (
          stripe_status IN ('active', 'trialing')
          AND (current_period_end IS NULL OR current_period_end >= now())
        )
      )
  );
$$;

CREATE OR REPLACE FUNCTION public.morpheus_plan_limit(target_clinic UUID, limit_name TEXT)
RETURNS INTEGER
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT CASE COALESCE(plan_id, 'essential')
    WHEN 'elite' THEN CASE limit_name WHEN 'rooms' THEN 10 WHEN 'doctors' THEN 20 WHEN 'workspaces' THEN 5 ELSE 0 END
    WHEN 'pro' THEN CASE limit_name WHEN 'rooms' THEN 6 WHEN 'doctors' THEN 15 WHEN 'workspaces' THEN 3 ELSE 0 END
    ELSE CASE limit_name WHEN 'rooms' THEN 3 WHEN 'doctors' THEN 10 WHEN 'workspaces' THEN 1 ELSE 0 END
  END
  FROM public.clinics
  WHERE id = target_clinic;
$$;

CREATE OR REPLACE FUNCTION public.handle_morpheus_auth_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.users (id, email, password_hash, display_name)
  VALUES (
    NEW.id,
    lower(COALESCE(NEW.email, '')),
    '',
    COALESCE(NULLIF(NEW.raw_user_meta_data->>'display_name', ''), NULLIF(NEW.raw_user_meta_data->>'full_name', ''), split_part(COALESCE(NEW.email, 'usuario'), '@', 1))
  )
  ON CONFLICT (id) DO UPDATE SET
    email = EXCLUDED.email,
    display_name = COALESCE(NULLIF(public.users.display_name, ''), EXCLUDED.display_name),
    updated_at = now();
  RETURN NEW;
END;
$$;

