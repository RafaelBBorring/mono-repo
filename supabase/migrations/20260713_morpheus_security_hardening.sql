DROP TRIGGER IF EXISTS psychologists_plan_limit ON public.psychologists;
CREATE TRIGGER psychologists_plan_limit BEFORE INSERT ON public.psychologists FOR EACH ROW EXECUTE FUNCTION public.enforce_morpheus_entity_limits();

CREATE OR REPLACE FUNCTION public.prevent_morpheus_reservation_conflict()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF NEW.start_time !~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'
     OR NEW.end_time !~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'
     OR NEW.start_time >= NEW.end_time THEN
    RAISE EXCEPTION 'invalid_reservation_time';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtext(NEW.clinic_id::text || ':' || NEW.room_id::text || ':' || NEW.date::text));
  IF EXISTS (
    SELECT 1 FROM public.reservations
    WHERE clinic_id = NEW.clinic_id AND room_id = NEW.room_id AND date = NEW.date
      AND id <> COALESCE(NEW.id, '')
      AND NEW.start_time < end_time AND NEW.end_time > start_time
  ) THEN RAISE EXCEPTION 'reservation_conflict'; END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS reservations_prevent_conflict ON public.reservations;
CREATE TRIGGER reservations_prevent_conflict BEFORE INSERT OR UPDATE ON public.reservations
FOR EACH ROW EXECUTE FUNCTION public.prevent_morpheus_reservation_conflict();

CREATE OR REPLACE FUNCTION public.audit_morpheus_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE source JSONB; target_clinic UUID; target_id TEXT;
BEGIN
  source := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
  target_clinic := NULLIF(source->>'clinic_id', '')::uuid;
  target_id := source->>'id';
  INSERT INTO public.morpheus_audit_log (clinic_id, table_name, operation, record_id, old_data, new_data)
  VALUES (target_clinic, TG_TABLE_NAME, TG_OP, target_id, CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN to_jsonb(OLD) END, CASE WHEN TG_OP IN ('INSERT', 'UPDATE') THEN to_jsonb(NEW) END);
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

