function makeGrimorio(knowledgeKey, tier, overrides = {}) {
  const tierData = GRIMORIO_TIERS.find(t => t.id === tier)
  return {
    id: `${knowledgeKey}-${tier}`,
    name: '',
    description: '',
    image: '',
    knowledgeKey,
    tier,
    maxCircle: tierData?.maxCircle || 2,
    isPublic: true,
    isDefault: true,
    sourceKind: 'neutro',
    sourceName: '',
    category: '',
    rituals: [],
    ...overrides,
  }
}

